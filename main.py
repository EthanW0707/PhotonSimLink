# 3. Deterministic Verification Script
def verify_parameters(params: dict):
    errors = []
    cfg = params.get('config', {})
    prop = cfg.get('prop', [])

    if not cfg or 'nphoton' not in cfg:
        errors.append("The simulation configuration structure is missing the mandatory 'nphoton' execution key.")
        return False, "\n".join(errors)

    for idx, layer in enumerate(prop):
        if len(layer) != 4:
            errors.append(f"Layer {idx} is invalid. Expected 4 metrics [mua, mus, g, n], received {len(layer)}.")
            continue

        mua, mus, g, n = layer[0], layer[1], layer[2], layer[3]

        if idx == 0 and mua == 0 and mus == 0:
            continue

        if mua < 0 or mua > 5.0:
            errors.append(f"Layer {idx} Absorption (mua={mua}) violates constraints (Must be 0.0 to 5.0).")
        if mus <= 0 or mus > 500:
            errors.append(f"Layer {idx} Scattering (mus={mus}) violates constraints (Must be 0.0 to 500).")
        if g < 0 or g >= 1:
            errors.append(f"Layer {idx} Anisotropy (g={g}) violates constraints (Must be 0.0 to <1.0).")
        if n < 1.0 or n > 1.6:
            errors.append(f"Layer {idx} Refractive Index (n={n}) violates constraints (Must be 1.0 to 1.6).")

    if errors:
        return False, "\n".join(errors)
    return True, "Parameters verified successfully."

