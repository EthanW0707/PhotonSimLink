# Core Biophotonics Calculation Functions (fallback path)
def calculate_mua_beer_lambert(wavelength_nm, hb_conc_uM=30.0, hbo2_conc_uM=70.0):
    eps_hb_uM = (32000.0 * np.exp(-0.004 * wavelength_nm) + 500.0) * 1e-6
    eps_hbo2_uM = (15000.0 * np.exp(-0.002 * wavelength_nm) + 200.0) * 1e-6
    mua_cm_inv = 2.303 * ((eps_hb_uM * hb_conc_uM) + (eps_hbo2_uM * hbo2_conc_uM))
    return float(mua_cm_inv / 10.0)

def calculate_mus_from_wavelength(wavelength_nm):
    a_mie = 200.0
    b_mie = 1.5
    ref_wavelength = 500.0
    mus_cm_inv = a_mie * ((wavelength_nm / ref_wavelength) ** (-b_mie))
    return float(mus_cm_inv / 10.0)

# Optical Property Resolver (pVTS with Math Fallback)
def resolve_optical_properties(wavelength_nm, tissue_type=None):
    """
    Attempts to pull properties from the real pVTS Tissue/chromophore/scatterer
    chain first. If pVTS isn't loaded, fails, or the database lookup errors,
    falls back to the Beer-Lambert/power-law math approximation.

    NOTE: previously this called `SpectralDatabase.get_properties(wavelength_nm)`,
    a method that never existed on SpectralDatabase (it only has
    get_extinction_coefficient/get_spectrum_value/register_spectrum/get_spectrum).
    That call always raised AttributeError and silently fell through to the
    math fallback -- meaning pVTS was NEVER actually used, regardless of
    whether the rest of the pVTS package worked correctly. This is now wired
    to the real Tissue class instead.

    Returns physical mus (not reduced mus') since that's what pmcx's
    cfg.prop = [mua, mus, g, n] convention expects.
    """
    global pVTS_loaded_successfully

    if tissue_type is None and TissueType is not None:
        tissue_type = TissueType.Skin

    if pVTS_loaded_successfully and Tissue is not None:
        try:
            tissue = Tissue(tissue_type=tissue_type)
            mua = tissue.get_mua(wavelength_nm)
            mus = tissue.get_mus(wavelength_nm)   # physical mus, NOT musp -- pmcx needs this one
            g = tissue.get_g(wavelength_nm)
            n = tissue.n
            return [float(mua), float(mus), float(g), float(n)], "pVTS Database Lookup (Primary C# Port)"
        except Exception as pvts_err:
            print(f"[pVTS resolver failed]: {pvts_err}")

    # Fallback Triggered Explicitly
    mua = calculate_mua_beer_lambert(wavelength_nm)
    mus = calculate_mus_from_wavelength(wavelength_nm)
    return [mua, mus, 0.90, 1.40], "⚠️ FALLBACK ACTIVATED: Beer-Lambert & Mie Scattering Math Engine"

